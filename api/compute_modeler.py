from __future__ import annotations

import json
import re
from datetime import datetime, timezone
from decimal import Decimal
from math import isfinite
from typing import Any

from .calculator import TERM_DAYS


def calculate_compute_model(
    *, period_hours: float, compute_hours: float, payg_rate: float,
    discount_percent: float, hourly_commitment: float, currency_code: str, term: str,
) -> dict[str, Any]:
    """Model a single constant-rate workload, including idle-hour commitment."""
    inputs = {
        "Period hours": period_hours, "Compute hours": compute_hours,
        "PAYG rate": payg_rate, "Discount percent": discount_percent,
        "Hourly commitment": hourly_commitment,
    }
    for label, value in inputs.items():
        if isinstance(value, bool) or not isinstance(value, (int, float)) or not isfinite(value):
            raise ValueError(f"{label} must be a finite number.")
        if value < 0 or value > 1_000_000_000:
            raise ValueError(f"{label} must be between zero and 1,000,000,000.")
    if term not in TERM_DAYS:
        raise ValueError("Select a P1Y or P3Y term.")
    if not isinstance(currency_code, str) or not re.fullmatch(r"[A-Z]{3}", currency_code):
        raise ValueError("Enter a three-letter uppercase currency code.")
    term_hours = 24 * TERM_DAYS[term]
    if not 0 < period_hours <= term_hours:
        raise ValueError(f"Period hours must be greater than zero and at most {term_hours} for this term.")
    if compute_hours > period_hours:
        raise ValueError("Compute hours cannot exceed period hours for this single-workload model.")
    if payg_rate <= 0:
        raise ValueError("PAYG rate must be greater than zero.")
    if discount_percent >= 100:
        raise ValueError("Discount percent must be at least zero and less than 100.")
    if payg_rate < 0.000000001 or (0 < hourly_commitment < 0.000000001):
        raise ValueError("Positive monetary rates must be at least 0.000000001 per hour.")

    period, runtime, rate, discount, commitment = (
        Decimal(str(value)) for value in (period_hours, compute_hours, payg_rate, discount_percent, hourly_commitment)
    )
    factor = 1 - discount / 100
    avoided_payg_per_hour = min(rate, commitment / factor)
    committed_cost = commitment * period
    break_even = committed_cost / avoided_payg_per_hour if avoided_payg_per_hour else None
    maximum_savings = period * avoided_payg_per_hour - committed_cost
    attainable = break_even is not None and break_even <= period

    def costs(hours: Decimal) -> dict[str, float]:
        baseline = hours * rate
        remaining = hours * (rate - avoided_payg_per_hour)
        used = hours * avoided_payg_per_hour * factor
        modeled = committed_cost + remaining
        savings = baseline - modeled
        return {
            "computeHours": float(hours), "baselineCost": float(baseline),
            "modeledCost": float(modeled), "savingsAmount": float(savings),
            "remainingPaygCost": float(remaining),
            "unusedCommitment": float(max(Decimal(0), committed_cost - used)),
            "savingsPercent": float(savings / baseline * 100) if baseline else 0.0,
            "coveragePercent": float(avoided_payg_per_hour / rate * 100) if hours else 0.0,
            "utilizationPercent": float(used / committed_cost * 100) if committed_cost else 0.0,
        }

    actual = costs(runtime)
    outcome = "Savings" if actual["savingsAmount"] > 0 else "Loss" if actual["savingsAmount"] < 0 else "Break-even"
    guidance = [
        "Calculation-based guidance, not generated by Copilot. No data has been sent to an AI service.",
        f"You pay {float(commitment):,.6f} {currency_code} every elapsed hour, including idle hours: "
        f"{float(committed_cost):,.2f} {currency_code} across {period_hours:g} period hours.",
        f"Projected PAYG cost is {actual['baselineCost']:,.2f} {currency_code}; commitment plus uncovered "
        f"PAYG is {actual['modeledCost']:,.2f} {currency_code}. Net savings (negative means loss): "
        f"{actual['savingsAmount']:,.2f} {currency_code}.",
    ]
    if break_even is None:
        guidance.append("With zero commitment there is no discount coverage, no commitment cost, and no savings. "
                        "There is no meaningful break-even runtime threshold.")
    else:
        guidance.append(
            "Break-even running hours = (hourly commitment x period hours) / "
            "min(PAYG hourly rate, hourly commitment / (1 - discount / 100))."
        )
        guidance.append(
            f"Break-even requires {float(break_even):,.6f} running hours "
            f"({float(break_even / period * 100):,.4f}% of this period). "
            + ("This exceeds available hours, so this commitment cannot break even for this workload."
               if not attainable else
               "Savings require runtime above this threshold."
               if maximum_savings > 0 else
               "Only break-even is possible at full runtime; no positive savings are possible.")
        )
        guidance.append(
            f"At your runtime, the margin above break-even is {float(runtime - break_even):,.6f} hours. "
            "This is a utilization threshold over the whole period, not a promise of payback after that many elapsed hours."
        )
    guidance.extend([
        f"Unused commitment is {actual['unusedCommitment']:,.2f} {currency_code}; "
        f"uncovered PAYG is {actual['remainingPaygCost']:,.2f} {currency_code}. "
        "Unused hourly commitment does not roll over. A smaller commitment can reduce idle-cost risk but covers less usage.",
        "Validate the rate, eligibility, discount, utilization pattern and authoritative Azure recommendation before purchase. "
        "Compute hours alone cannot establish a discount or a recommended commitment.",
    ])
    assumptions = [
        "Offline user-input estimate; not live Azure pricing or an Azure purchase recommendation.",
        "One workload runs at a constant eligible PAYG cost per running hour, without parallel instances.",
        "Fractional running hours are allowed. The workload is off for the remainder of the period.",
        "The stated effective discount applies uniformly to covered usage; uncovered usage stays at PAYG.",
        "Commitment is charged every elapsed hour, including idle hours; unused hourly amounts do not roll over.",
        "No other workloads consume unused commitment. Taxes, support, licenses and ineligible charges are excluded.",
        f"Full-term projections repeat this duty cycle and rates for {term_hours} hours "
        "(365 days/year); this is not a forecast and does not allow cancellation when the modeled period ends.",
        f"User-supplied PAYG rate: {payg_rate:g} {currency_code}/running hour; discount: {discount_percent:g}%.",
    ]
    points = {Decimal(0), period / 2, period, runtime}
    if break_even is not None and attainable:
        points.add(break_even)
    return {
        "mode": "modeler", "source": "Local compute-hours planning model",
        "collectedAt": datetime.now(timezone.utc).isoformat(),
        "currencyCode": currency_code, "term": term, "periodHours": period_hours,
        "paygRate": payg_rate, "discountPercent": discount_percent, "hourlyCommitment": hourly_commitment,
        "commitmentCost": float(committed_cost), "termHours": term_hours, **actual,
        "breakEvenHours": float(break_even) if break_even is not None else None,
        "breakEvenRuntimePercent": float(break_even / period * 100) if break_even is not None else None,
        "breakEvenAttainable": attainable, "positiveSavingsPossible": maximum_savings > 0,
        "runtimeMarginHours": float(runtime - break_even) if break_even is not None else None,
        "projectedTermBaselineCost": float(runtime * rate * term_hours / period),
        "projectedTermModeledCost": float((committed_cost + runtime * (rate - avoided_payg_per_hour)) * term_hours / period),
        "projectedTermSavings": float((runtime * avoided_payg_per_hour - committed_cost) * term_hours / period),
        "outcome": outcome, "guidance": guidance, "assumptions": assumptions,
        "sensitivity": [costs(hours) for hours in sorted(points)],
    }


def copilot_prompt(result: dict[str, Any]) -> str:
    if result.get("mode") != "modeler":
        raise ValueError("Run a compute-hours model before preparing Copilot guidance.")
    return (
        "Explain this offline Azure Savings Plan compute-hours model in plain language. "
        "Use only the supplied calculated figures; do not invent prices, discounts or live recommendations. "
        "Explain break-even runtime versus elapsed commitment hours, idle-hour risk, uncovered PAYG, "
        "and why savings may be negative. Acknowledge that full-term projections repeat the duty cycle "
        "and that Copilot has not verified Azure eligibility. Suggest questions to validate before purchase, "
        "not purchase instructions. If break-even is unattainable or commitment is zero, say so. "
        "Do not recompute or change the supplied financial figures.\n\n"
        + json.dumps(result, indent=2, allow_nan=False)
    )
